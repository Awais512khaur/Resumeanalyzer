<?php
require_once __DIR__ . '/../../config/session.php';

require_once __DIR__ . "/../../config/config.php";
require_once __DIR__ . "/../../config/db.php";
require_once __DIR__ . "/../../config/audit.php";

// ✅ UPDATED PATH
require_once __DIR__ . "/../../tools/tcpdf/tcpdf.php";

// VALIDATE
if (!filter_var($_GET['id'] ?? null, FILTER_VALIDATE_INT)) {
    die("Invalid request");
}

$id = (int)$_GET['id'];

// GET RESULT
$stmt = $pdo->prepare("SELECT * FROM analysis_results WHERE id = ?");
$stmt->execute([$id]);
$result = $stmt->fetch();

if (!$result) {
    die("Result not found");
}
$ownerStatement = $pdo->prepare("SELECT user_id, file_name FROM resumes WHERE id = ?");
$ownerStatement->execute([(int)$result['resume_id']]);
$resumeOwner = $ownerStatement->fetch();
if (!$resumeOwner || (($_SESSION['role'] ?? '') !== 'admin' && (int)$resumeOwner['user_id'] !== (int)($_SESSION['user_id'] ?? 0))) {
    http_response_code(403);
    exit('You do not have permission to download this report.');
}
audit_log($pdo, 'analysis.report_downloaded', 'PDF report downloaded for resume: ' . $resumeOwner['file_name'], 'analysis', (int)$id);
// FORMAT KEYWORDS & SUGGESTIONS
$matchedArray = array_filter(explode(",", $result['matched_keywords']));
$missingArray = array_filter(explode(",", $result['missing_keywords']));
$matchedFormatted = !empty($matchedArray) ? htmlspecialchars(implode(", ", $matchedArray)) : "None";
$missingFormatted = !empty($missingArray) ? htmlspecialchars(implode(", ", $missingArray)) : "None";

$suggestionsList = explode(" | ", $result['suggestions']);
$suggestionsHtml = "<ul style='line-height: 1.6; color: #374151;'>";
foreach ($suggestionsList as $s) {
    if (!empty(trim($s))) {
        $suggestionsHtml .= "<li style='margin-bottom: 6px;'>" . htmlspecialchars(trim($s)) . "</li>";
    }
}
$suggestionsHtml .= "</ul>";

// CREATE PDF
$pdf = new TCPDF();

// DOCUMENT SETTINGS
$pdf->SetCreator("Resume Analyzer");
$pdf->SetAuthor("ResumeAI");
$pdf->SetTitle("Resume Analysis Report");

// REMOVE DEFAULT HEADER/FOOTER
$pdf->setPrintHeader(false);
$pdf->setPrintFooter(false);

// ADD PAGE
$pdf->AddPage();

// STYLED HTML CONTENT
$html = "
<h1 style='color:#2563eb;'>Resume Analysis Report</h1>
<p style='color:#6b7280; font-size:11px;'>Generated on " . date('F j, Y, g:i a') . "</p>
<hr>

<h3>Scores</h3>
<p><strong>Resume Score:</strong> {$result['score']}%</p>
<p><strong>ATS Score:</strong> {$result['ats_score']}%</p>

<hr>

<h3 style='color:#16a34a;'>Matched Keywords</h3>
<p style='color:#374151; font-size:11px;'>{$matchedFormatted}</p>

<h3 style='color:#dc2626;'>Missing Keywords</h3>
<p style='color:#374151; font-size:11px;'>{$missingFormatted}</p>

<hr>

<h3 style='color:#d97706;'>AI Recommendations & Suggestions</h3>
{$suggestionsHtml}

<hr>

<p style='font-size:10px;color:gray;'>
Generated by AI Resume Analyzer System
</p>
";

// WRITE CONTENT
$pdf->writeHTML($html, true, false, true, false, '');

// DOWNLOAD FILE
header('Cache-Control: private, no-store, no-cache, must-revalidate, max-age=0');
$pdf->Output("resume_analysis_report.pdf", "D");

exit;
